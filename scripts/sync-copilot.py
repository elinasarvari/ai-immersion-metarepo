#!/usr/bin/env python3
"""Keep GitHub Copilot's files in step with the shared sources.

  CLAUDE.md               -> .github/copilot-instructions.md   (copy)
  skills/<name>/SKILL.md  -> .github/prompts/<name>.prompt.md  (slash command that runs the skill)

Skills and lane agents themselves are shared through the .github/skills and .github/agents symlinks.

Usage: python3 scripts/sync-copilot.py [--check]
  --check  change nothing; exit 1 if any Copilot file is missing or out of date.
"""
import json, re, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
check = "--check" in sys.argv[1:]
stale = []

def write(path: Path, text: str) -> None:
    if path.exists() and path.read_text() == text:
        return
    stale.append(str(path.relative_to(root)))
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

def frontmatter(md: str) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", md, re.S)
    out = {}
    for line in (m.group(1) if m else "").splitlines():
        k, sep, v = line.partition(":")
        if sep and not line.startswith((" ", "\t")):
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out

# 1. Instructions
write(root / ".github/copilot-instructions.md", (root / "CLAUDE.md").read_text())

# 2. Prompt files, one per skill
prompts = root / ".github/prompts"
wanted = set()
for skill_md in sorted((root / "skills").glob("*/SKILL.md")):
    meta = frontmatter(skill_md.read_text())
    name = meta.get("name") or skill_md.parent.name
    desc = meta.get("description", f"Run the {name} skill")
    wanted.add(f"{name}.prompt.md")
    write(prompts / f"{name}.prompt.md", f"""---
description: {json.dumps(desc)}
agent: agent
---
<!-- Generated by scripts/sync-copilot.py from skills/{skill_md.parent.name}/SKILL.md. Don't edit; edit the skill and rerun. -->

Use the **{name}** skill: read [SKILL.md](../../skills/{skill_md.parent.name}/SKILL.md) and follow it exactly, applying it to the request that follows this command. Run any scripts it mentions from the repository root.
""")

# 3. Remove prompt files for skills that no longer exist
for p in prompts.glob("*.prompt.md") if prompts.exists() else []:
    if p.name not in wanted and "Generated by scripts/sync-copilot.py" in p.read_text():
        stale.append(f"{p.relative_to(root)} (removed)")
        if not check:
            p.unlink()

if stale:
    print(("Out of date:" if check else "Updated:"), *stale, sep="\n  ")
else:
    print("Copilot files are up to date.")
sys.exit(1 if (check and stale) else 0)
